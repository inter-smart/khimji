export async function GET(request) {
  try {
    // Get query parameters
    const { searchParams } = new URL(request.url);
    const categoryId = parseInt(searchParams.get("category_id") || "1");
    const perPage = parseInt(searchParams.get("per_page") || "10");
    const page = parseInt(searchParams.get("page") || "1");

    // Filter archives by category
    const filteredArchives = DUMMY_ARCHIVES.filter((archive) => archive.category_id === categoryId);

    // Calculate pagination
    const total = filteredArchives.length;
    const lastPage = Math.ceil(total / perPage);
    const startIndex = (page - 1) * perPage;
    const endIndex = startIndex + perPage;

    // Get paginated archives
    const paginatedArchives = filteredArchives.slice(startIndex, endIndex);

    // Return response in the expected format
    return NextResponse.json({
      data: {
        archives: paginatedArchives,
        pagination: {
          total: total,
          per_page: perPage,
          current_page: page,
          last_page: lastPage,
          has_more_pages: page < lastPage,
        },
      },
    });
  } catch (error) {
    return NextResponse.json(
      {
        error: "Failed to fetch archives",
        message: error.message,
      },
      { status: 500 }
    );
  }
}
